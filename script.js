const setDepartment = (department) => {
  departmentField.value = department;
  whatsappRequest.hidden = true;
  formMessage.textContent = "";
};

const searchDepartment = (query) => {
  const normalizedQuery = query.trim().toLocaleLowerCase();
  if (!normalizedQuery) {
    voiceStatus.textContent = textFor("Enter or say a symptom or department to search.");
    return;
  }

  const result = departmentSearchTerms.find(({ terms }) =>
    terms.some((term) => normalizedQuery.includes(term.toLocaleLowerCase()))
  );

  if (!result) {
    voiceStatus.textContent = textFor("No matching department found. Please call our care team for help.");
    return;
  }

  setDepartment(result.department);
  if (result.department === "Emergency Care") {
    voiceStatus.textContent = textFor("For urgent symptoms or serious injury, call our emergency line now.");
    document.querySelector("#triage").scrollIntoView({ behavior: "smooth" });
    return;
  }

  voiceStatus.textContent = languageSelect.value === "kn"
    ? `${departmentName(result.department)} ಆಯ್ಕೆಯಾಗಿದೆ. ವಿಭಾಗದ ಕಾರ್ಡ್ ಆಯ್ಕೆಮಾಡಿ ಅಥವಾ ಅಪಾಯಿಂಟ್‌ಮೆಂಟ್ ವಿನಂತಿಯನ್ನು ಮುಂದುವರಿಸಿ.`
    : `${result.department} selected. Choose a department card or continue to your appointment request.`;
  document.querySelector("#specialties").scrollIntoView({ behavior: "smooth" });
};

